-- 0015_add_embedding_bge_m3_indexes.sql — bge-m3 embedding 欄位的 HNSW index
--
-- ⚠️ 套「兩側」DB（project + personal）：observations/project_memories 是共用
--   Drizzle schema 表，schema.ts 宣告這兩個 index。
--
-- 建議在 bge-m3 backfill「之後」套用：pgvector 建 HNSW 時 bulk build 遠快於
--   逐筆增量插入，先建 index 再回填會慢很多。
--
-- CREATE INDEX CONCURRENTLY 不能在 transaction 內跑：
--   apply-migration.ts / test-db-setup.ts 以 simple query protocol 逐 chunk 執行、
--   不包 transaction（多 statement chunk 會隱含 transaction，所以這裡每個 chunk
--   刻意只放一條 statement，不附 SET）。
--
-- 套用後確認 index 有效：
--   SELECT c.relname, i.indisvalid FROM pg_index i
--     JOIN pg_class c ON c.oid = i.indexrelid
--     WHERE c.relname IN ('embedding_bge_m3_idx','observations_embedding_bge_m3_idx');
--   若 indisvalid = false（CONCURRENTLY 中斷）：DROP INDEX CONCURRENTLY IF EXISTS
--   後重跑本檔。
--
--   rollback：
--     DROP INDEX CONCURRENTLY IF EXISTS embedding_bge_m3_idx;
--     DROP INDEX CONCURRENTLY IF EXISTS observations_embedding_bge_m3_idx;
--
-- 套用方式（兩側都要跑）：
--   DATABASE_URL=<project-db-url>  tsx scripts/apply-migration.ts sql/migrations/0015_add_embedding_bge_m3_indexes.sql
--   DATABASE_URL=<personal-db-url> tsx scripts/apply-migration.ts sql/migrations/0015_add_embedding_bge_m3_indexes.sql

CREATE INDEX CONCURRENTLY IF NOT EXISTS "embedding_bge_m3_idx" ON "project_memories" USING hnsw ("embedding_bge_m3" vector_cosine_ops);
--> statement-breakpoint
CREATE INDEX CONCURRENTLY IF NOT EXISTS "observations_embedding_bge_m3_idx" ON "observations" USING hnsw ("embedding_bge_m3" vector_cosine_ops);
